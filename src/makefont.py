def glyph_rows(rows, xoff=1):
    out = []
    for y in range(8):
        r = rows[y] if y < len(rows) else ""
        b = 0
        for x, ch in enumerate(r):
            if ch == '#':
                b |= 0x80 >> (x + xoff)
        out.append(b)
    return out

SPECIAL = {
    128: [0x00, 0x00, 0xFF, 0x81, 0x81, 0xFF, 0x00, 0x00],  # Balken leer
    129: [0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00],  # Balken voll
    130: [0x00, 0x60, 0x78, 0x7E, 0x78, 0x60, 0x00, 0x00],  # Cursor-Pfeil
    131: [0x0F, 0x09, 0x09, 0x09, 0x39, 0x7B, 0x33, 0x00],  # Note
    132: [0x40, 0x60, 0x70, 0x78, 0x70, 0x60, 0x40, 0x00],  # Play
    133: [0x00, 0x6C, 0x6C, 0x6C, 0x6C, 0x6C, 0x6C, 0x00],  # Pause
    134: [0x00, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00],  # Stop
    135: [0xFF, 0x00, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00],  # Doppellinie
}

def build():
    tiles = []
    for code in range(136):
        if code in SPECIAL:
            rows = SPECIAL[code]
        else:
            ch = chr(code)
            if ch.islower():
                ch = ch.upper()
            if 32 <= code < 128:
                rows = glyph_rows(G.get(ch, G['?']))
            else:
                rows = [0] * 8
        for b in rows:
            tiles += [b, b]  # beide Bitplanes -> Farbe 3
    return bytes(tiles)

if __name__ == "__main__":
    open(sys.argv[1], "wb").write(build())
